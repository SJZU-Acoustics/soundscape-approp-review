#!/usr/bin/env python3
"""build_si_tables.py -- regenerate the Supplementary Information tables (S1 full
report list, S2 non-pooled families) from the deposited data in intermediate/.
Outputs -> output/tables/.
"""
import pandas as pd, pathlib, re

ROOT = pathlib.Path(__file__).resolve().parents[1]
INT  = ROOT / "intermediate"
OUT  = ROOT / "output" / "tables"
OUT.mkdir(parents=True, exist_ok=True)


def esc(s):
    s = str(s)
    return (s.replace("\\", r"\textbackslash{}").replace("&", r"\&").replace("%", r"\%")
             .replace("_", r"\_").replace("#", r"\#"))


# ----------------------------------------------------------- Table S1 (full reports)
st = pd.read_csv(INT / "report_characteristics.csv")
st["country"] = st["country"].replace({"Türkiye": "Turkey"})
st["year"] = pd.to_numeric(st["year"], errors="coerce")
st["n_participants"] = pd.to_numeric(st["n_participants"], errors="coerce")
set_ab = {"outdoor": "O", "indoor": "I", "both": "B"}
met_ab = {"in-situ-survey": "in-situ", "soundwalk": "walk", "ex-situ-lab": "lab",
          "VR-immersive": "VR", "online-survey": "online"}
des_ab = {"cross-sectional": "CS", "experimental": "Exp", "mixed": "Mix"}
ins_ab = {"single-ISO-item": "ISO-1", "per-source-appropriateness": "per-src",
          "multi-item-scale": "multi"}
rob_ab = {"high": "High", "some-concerns": "Some", "low": "Low"}
clu_ab = {"canonical": "", "shared-with-canonical": "$\\dagger$"}

st = st.sort_values("study_id")
rowsS1 = []
for _, r in st.iterrows():
    n = r.get("n_participants")
    n = "--" if pd.isna(n) else f"{int(n)}"
    flag = clu_ab.get(str(r.get("cluster_role_P11_5", "")), "")
    rowsS1.append(" & ".join([
        esc(r.study_id) + flag, str(int(r.year)), esc(r.country),
        set_ab.get(r.setting_indoor_outdoor, esc(r.setting_indoor_outdoor)),
        esc(str(r.space_function).capitalize()),
        met_ab.get(r.method, esc(r.method)),
        des_ab.get(r.study_design, esc(r.study_design)),
        n,
        ins_ab.get(r.SA_construct_status, esc(r.SA_construct_status)),
        rob_ab.get(r.RoB_overall, esc(r.RoB_overall)),
    ]) + r" \\")

tS1 = r"""% Auto-generated by build_si_tables.py -- do not edit by hand.
{\footnotesize
\setlength{\tabcolsep}{4pt}
\begin{longtable}{@{}lllccllrll@{}}
\caption{Characteristics of the 67 included empirical reports (54 independent studies), sorted by
identifier.}\label{tab:S1}\\
\toprule
Report & Yr & Country & Set & Function & Method & Des & $n$ & Instr & RoB \\
\midrule
\endfirsthead
\multicolumn{10}{@{}l}{\footnotesize\itshape Table~\ref{tab:S1} continued} \\
\toprule
Report & Yr & Country & Set & Function & Method & Des & $n$ & Instr & RoB \\
\midrule
\endhead
\midrule \multicolumn{10}{r@{}}{\footnotesize continued on next page} \\
\endfoot
\bottomrule
\endlastfoot
""" + "\n".join(rowsS1) + r"""
\end{longtable}
}

\noindent{\footnotesize Identifiers are the in-text citation keys; full references are in the main
article. $\dagger$ marks a report that shares its dataset with another report (a non-canonical member
of a shared-dataset cluster); such reports inform the narrative individually but contribute as a single
study to any pooled estimate. Setting: O outdoor, I indoor, B both. Method: in-situ survey, soundwalk,
ex-situ laboratory (lab), virtual-reality or immersive (VR), online. Design: CS cross-sectional,
Exp experimental, Mix mixed. Instrument: ISO-1 single ISO/TS 12913 item, per-src per-source item,
multi multi-item scale. RoB overall risk of bias.\par}
"""
(OUT / "tableS1_reports.tex").write_text(tS1)


# ----------------------------------------------------------- Table S2 (non-pooled comparable)
nf = pd.read_csv(INT / "nonpooled_families.csv")
nf["rows"] = pd.to_numeric(nf["rows"], errors="coerce")
nf["studies"] = pd.to_numeric(nf["studies"], errors="coerce")
comp = nf[nf.evidence_set == "comparable but below pooling threshold"].copy()
comp = comp.sort_values("pool_name")
rowsS2 = []
for _, r in comp.iterrows():
    ids = str(r.study_ids).replace(";", ",")
    rowsS2.append(" & ".join([
        esc(r.pool_name), str(int(r.rows)), str(int(r.studies)),
        esc(str(r.direction_summary)), esc(ids),
    ]) + r" \\")
tS2 = r"""% Auto-generated by build_si_tables.py -- do not edit by hand.
\begin{table}[htbp]
\centering
\caption{Source and acoustic-index families that were comparable but fell below the five-study pooling
threshold, reported narratively (RQ2). Rows is the number of comparable extracted estimates; Studies is
the number of independent studies contributing them.}
\label{tab:S2}
\footnotesize
\setlength{\tabcolsep}{5pt}
\begin{tabular}{@{}lccp{3.6cm}p{4.4cm}@{}}
\toprule
Family & Rows & Studies & Direction & Contributing studies \\
\midrule
""" + "\n".join(rowsS2) + r"""
\bottomrule
\end{tabular}
\end{table}
"""
(OUT / "tableS2_nonpooled.tex").write_text(tS2)

print("Wrote SI tables to", OUT)
